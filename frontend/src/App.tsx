import { useState } from 'react';
import { GlobeMap } from './components/GlobeMap';
import { Header, type NavigationTab } from './components/Header';
import { SearchBar, type SearchTarget } from './components/SearchBar';
import { DispatchPanel } from './components/DispatchPanel';
import { RoutePreviewCard } from './components/RoutePreviewCard';
import { AlgorithmHUD } from './components/AlgorithmHUD';
import { FleetTelemetryDrawer } from './components/FleetTelemetryDrawer';
import { DispatchInspectorDrawer } from './components/DispatchInspectorDrawer';
import { useMapReady } from './hooks/useMapReady';
import { usePlaceSearch } from './hooks/usePlaceSearch';
import { useSimulatedDrivers } from './hooks/useSimulatedDrivers';
import { useDispatch } from './hooks/useDispatch';
import { useDispatchTrace } from './hooks/useDispatchTrace';
import { useRoute } from './hooks/useRoute';
import { useDriverApproach } from './hooks/useDriverApproach';
import { useVehicleAnimation } from './hooks/useVehicleAnimation';
import type { PlaceSuggestion } from './types/place';
import type { SimulatedDriver } from './types/driver';

/**
 * Root application component.
 *
 * State topology:
 *   - mapState         : map load lifecycle (loading → ready | error)
 *   - search           : query, suggestions, and search status from usePlaceSearch
 *   - activeTarget     : 'pickup' | 'destination' active search mode (Phase 11.1)
 *   - selectedPlace    : pickup place; drives globe camera, pin marker, and simulated fleet
 *   - destinationPlace : destination place; drives route calculation and preview (Phase 11.1)
 *   - routeState       : road-network route, distance, duration, and fares (Phase 11.1)
 *   - drivers          : deterministic simulated drivers generated for selectedPlace (Phase 7C)
 *   - dispatchState    : real backend dispatch lifecycle with full trip progression (Phase 11.3)
 *   - driverApproach   : road route from assigned driver origin to pickup (Phase 11.2)
 *   - approachAnimation: vehicle animation along approach route to pickup (Phase 11.2)
 *   - tripAnimation    : vehicle animation along road route to destination (Phase 11.3)
 *   - traceState       : read-only dispatch execution trace (Phase 11.4F lifted to App)
 *   - isTraceExpanded  : whether dispatch trace accordion is expanded (controls map overlays)
 *   - isAlgorithmMode  : whether live algorithm visualizer overlays and HUD are active
 *   - replayPulseToken : numeric token to re-trigger wavefront shortest path animations
 */
const SHOWCASE_PLACE: PlaceSuggestion = {
  id: 'showcase-london',
  name: 'Central London, United Kingdom',
  subtitle: 'Greater London, England, United Kingdom',
  lat: 51.5074,
  lon: -0.1276,
  type: 'city',
  bbox: [-0.25, 51.42, 0.02, 51.58],
};

export default function App() {
  const { state: mapState, onLoad, onError } = useMapReady();
  const search = usePlaceSearch();
  const [activeTab, setActiveTab] = useState<NavigationTab>('ride');
  const [activeTarget, setActiveTarget] = useState<SearchTarget>('pickup');
  const [selectedPlace, setSelectedPlace] = useState<PlaceSuggestion | null>(null);
  const [destinationPlace, setDestinationPlace] = useState<PlaceSuggestion | null>(null);
  const [isTraceExpanded, setIsTraceExpanded] = useState(false);
  const [isAlgorithmMode, setIsAlgorithmMode] = useState(true);
  const [replayPulseToken, setReplayPulseToken] = useState(0);
  const [focusFleetToken, setFocusFleetToken] = useState(0);
  const [focusDriverLocation, setFocusDriverLocation] = useState<{ lon: number; lat: number } | null>(null);

  const drivers = useSimulatedDrivers(selectedPlace);
  const {
    dispatchState,
    requestDispatch,
    cancelRide,
    isCancelling,
    startRide,
    isStarting,
    completeRide,
    isCompleting,
    markArrived,
    reset: resetDispatch,
  } = useDispatch(selectedPlace, drivers);

  // Phase 11.4F: Single-fetch dispatch trace lifted to App.
  // Trace is generated by the matching engine when the batch completes.
  // Pre-match states ('submitting', 'polling') have not yet executed AuctionMatcher or written to DispatchTraceStore.
  // Only query the trace once the dispatch lifecycle has resolved to avoid premature 404 console errors.
  const isDispatchResolved =
    dispatchState.phase !== 'idle' &&
    dispatchState.phase !== 'submitting' &&
    dispatchState.phase !== 'polling';
  const activeTraceRequestId = isDispatchResolved ? dispatchState.requestId : null;
  const { state: traceState, refresh: refreshTrace } = useDispatchTrace(activeTraceRequestId);

  const { state: routeState, setSelectedTier, clearRoute } = useRoute(selectedPlace, destinationPlace);

  // Phase 11.2: Assigned driver road approach route
  const driverApproach = useDriverApproach(
    dispatchState.matchedDriverLocation,
    selectedPlace,
    dispatchState.phase === 'matched' || dispatchState.phase === 'en_route',
  );

  // Approach animation: vehicle travels from matched driver origin to pickup pin
  const approachAnimation = useVehicleAnimation({
    routeCoordinates: driverApproach.route?.coordinates ?? null,
    nominalDurationSeconds: driverApproach.route?.durationSeconds ?? 60,
    speedMultiplier: 8,
    isActive:
      (dispatchState.phase === 'matched' || dispatchState.phase === 'en_route') &&
      driverApproach.status === 'ready',
    onArrival: markArrived,
  });

  // Trip animation: vehicle travels from pickup to destination along road route
  const tripAnimation = useVehicleAnimation({
    routeCoordinates: routeState.route?.coordinates ?? null,
    nominalDurationSeconds: Math.min(routeState.route?.durationSeconds ?? 120, 240),
    speedMultiplier: 12,
    isActive: dispatchState.phase === 'in_progress' && !!routeState.route,
  });

  // Destination validation for starting the trip
  const canStartTrip = Boolean(
    destinationPlace &&
    routeState.route &&
    routeState.route.coordinates.length >= 2 &&
    routeState.status === 'ready'
  );

  const missingDestinationMessage = !destinationPlace
    ? 'Please select a destination using the search bar before starting your trip.'
    : routeState.status === 'error'
      ? (routeState.errorMessage || 'Unable to calculate road route to destination.')
      : routeState.status === 'loading'
        ? 'Calculating road route to destination…'
        : null;

  async function handleStartTrip() {
    if (!canStartTrip) {
      if (!destinationPlace) {
        setActiveTarget('destination');
      }
      return;
    }
    await startRide();
  }

  function handleSelect(place: PlaceSuggestion, target: SearchTarget = activeTarget) {
    if (target === 'pickup') {
      setSelectedPlace(place);
      search.setQuery(place.name);
      if (!destinationPlace) {
        setActiveTarget('destination');
        search.clearQuery();
      }
    } else {
      setDestinationPlace(place);
      search.setQuery(place.name);
    }
  }

  function handleSwap() {
    if (!selectedPlace || !destinationPlace) return;
    const prevPickup = selectedPlace;
    const prevDest = destinationPlace;
    setSelectedPlace(prevDest);
    setDestinationPlace(prevPickup);
    search.setQuery(activeTarget === 'pickup' ? prevDest.name : prevPickup.name);
  }

  function handleClearDestination() {
    setDestinationPlace(null);
    clearRoute();
    if (activeTarget === 'destination') {
      search.clearQuery();
      setActiveTarget('pickup');
    }
  }

  function handleClear() {
    if (activeTarget === 'pickup') {
      search.clearQuery();
      setSelectedPlace(null);
      setDestinationPlace(null);
      clearRoute();
      resetDispatch();
      setIsTraceExpanded(false);
    } else {
      handleClearDestination();
    }
  }

  function handleBookAnotherRide() {
    resetDispatch();
    setDestinationPlace(null);
    clearRoute();
    setActiveTarget('pickup');
    setIsTraceExpanded(false);
  }

  function handleSelectTab(tab: NavigationTab) {
    setActiveTab(tab);
    if (tab === 'fleet') {
      if (!selectedPlace) {
        setSelectedPlace(SHOWCASE_PLACE);
      }
      setFocusFleetToken((prev) => prev + 1);
    } else if (tab === 'dispatch') {
      if (!selectedPlace) {
        setSelectedPlace(SHOWCASE_PLACE);
      }
      setIsAlgorithmMode(true);
      setIsTraceExpanded(true);
    }
  }

  function handleFocusCluster() {
    setFocusFleetToken((prev) => prev + 1);
  }

  function handleFocusDriver(driver: SimulatedDriver) {
    setFocusDriverLocation({ lon: driver.lon, lat: driver.lat });
  }

  const hasDecidedTripRoute = Boolean(
    routeState.route &&
    routeState.route.coordinates &&
    routeState.route.coordinates.length >= 2
  );

  // Obsolete approach route and origin marker are hidden once trip starts or completes
  const activeApproachRoute =
    (dispatchState.phase === 'matched' || dispatchState.phase === 'en_route')
      ? (driverApproach.route?.coordinates ?? null)
      : null;

  const activeMatchedDriverLocation =
    (dispatchState.phase === 'matched' || dispatchState.phase === 'en_route')
      ? (driverApproach.route?.coordinates && driverApproach.route.coordinates.length > 0
          ? { lon: driverApproach.route.coordinates[0][0], lat: driverApproach.route.coordinates[0][1] }
          : hasDecidedTripRoute
            ? { lon: routeState.route!.coordinates[0][0], lat: routeState.route!.coordinates[0][1] }
            : dispatchState.matchedDriverLocation)
      : null;

  // Active vehicle marker position across lifecycle stages (strictly road snapped)
  const animatedVehiclePosition: [number, number] | null =
    dispatchState.phase === 'in_progress'
      ? (tripAnimation.currentPosition ??
         (hasDecidedTripRoute
           ? routeState.route!.coordinates[0]
           : (selectedPlace ? [selectedPlace.lon, selectedPlace.lat] : null)))
      : dispatchState.phase === 'arrived'
        ? (hasDecidedTripRoute
            ? routeState.route!.coordinates[0]
            : (selectedPlace ? [selectedPlace.lon, selectedPlace.lat] : null))
        : dispatchState.phase === 'completed'
          ? (hasDecidedTripRoute
              ? routeState.route!.coordinates[routeState.route!.coordinates.length - 1]
              : (destinationPlace ? [destinationPlace.lon, destinationPlace.lat] : null))
          : (dispatchState.phase === 'matched' || dispatchState.phase === 'en_route')
            ? (approachAnimation.currentPosition ??
               (driverApproach.route?.coordinates && driverApproach.route.coordinates.length > 0
                 ? driverApproach.route.coordinates[0]
                 : hasDecidedTripRoute
                   ? routeState.route!.coordinates[0]
                   : (activeMatchedDriverLocation ? [activeMatchedDriverLocation.lon, activeMatchedDriverLocation.lat] : null)))
            : null;

  const animatedVehicleBearing: number =
    dispatchState.phase === 'in_progress'
      ? tripAnimation.bearing
      : approachAnimation.bearing;

  const remainingDistanceMeters =
    dispatchState.phase === 'in_progress'
      ? tripAnimation.remainingDistanceMeters
      : approachAnimation.remainingDistanceMeters;

  const remainingDurationSeconds =
    dispatchState.phase === 'in_progress'
      ? tripAnimation.remainingDurationSeconds
      : approachAnimation.remainingDurationSeconds;

  return (
    <>
      <Header
        mapState={mapState}
        activeTab={activeTab}
        onSelectTab={handleSelectTab}
      />

      {/* ── Fleet Telemetry Drawer (Phase: Fleet tab) ────────────────────────── */}
      <FleetTelemetryDrawer
        isOpen={activeTab === 'fleet'}
        onClose={() => setActiveTab('ride')}
        drivers={drivers}
        placeName={selectedPlace?.name}
        onFocusDriver={handleFocusDriver}
        onFocusCluster={handleFocusCluster}
      />

      {/* ── Dispatch Engine & Cost Inspector Drawer (Phase: Dispatch tab) ────── */}
      <DispatchInspectorDrawer
        isOpen={activeTab === 'dispatch'}
        onClose={() => setActiveTab('ride')}
        traceState={traceState}
        onRefreshTrace={refreshTrace}
        isTraceExpanded={isTraceExpanded}
        onToggleTraceExpand={setIsTraceExpanded}
        onRunDiagnostic={requestDispatch}
        placeName={selectedPlace?.name}
      />

      {/* ── Standard Ride-booking inputs (hidden when inspecting Fleet or Dispatch drawers) ── */}
      {activeTab === 'ride' && (
        <SearchBar
          query={search.query}
          state={search.state}
          onQueryChange={search.setQuery}
          onClear={handleClear}
          onRetry={search.retry}
          onSelect={handleSelect}
          mapReady={mapState.status === 'ready'}
          activeTarget={activeTarget}
          onTargetChange={setActiveTarget}
          pickupPlace={selectedPlace}
          destinationPlace={destinationPlace}
          onSwap={handleSwap}
          onClearDestination={handleClearDestination}
        />
      )}

      <GlobeMap
        mapState={mapState}
        onLoad={onLoad}
        onError={onError}
        selectedPlace={selectedPlace}
        destinationPlace={destinationPlace}
        routeCoordinates={routeState.route?.coordinates ?? null}
        drivers={drivers}
        matchedDriverLocation={activeMatchedDriverLocation}
        matchedDriverId={dispatchState.matchedDriverId}
        driverApproachRoute={activeApproachRoute}
        animatedVehiclePosition={animatedVehiclePosition}
        animatedVehicleBearing={animatedVehicleBearing}
        activePhase={dispatchState.phase}
        trace={traceState.trace}
        showTraceOverlay={isAlgorithmMode || (isTraceExpanded && traceState.status === 'ready')}
        replayPulseToken={replayPulseToken}
        focusFleetToken={focusFleetToken}
        focusDriverLocation={focusDriverLocation}
        isFleetHighlighted={activeTab === 'fleet'}
      />

      {/* ── High-Tech Algorithm Visualizer HUD Overlay ───────────────────────── */}
      <AlgorithmHUD
        trace={traceState.trace}
        route={routeState.route}
        approachRoute={driverApproach.route}
        isAlgorithmMode={isAlgorithmMode}
        onToggleAlgorithmMode={() => setIsAlgorithmMode((prev) => !prev)}
        onReplayPathSearch={() => setReplayPulseToken((prev) => prev + 1)}
        matchedDriverId={dispatchState.matchedDriverId}
        phase={dispatchState.phase}
        hasDestination={Boolean(destinationPlace)}
        dockPosition={
          selectedPlace && destinationPlace && routeState.route && mapState.status === 'ready' && dispatchState.phase === 'idle'
            ? 'left'
            : 'right'
        }
        forceOpen={activeTab === 'dispatch'}
      />

      {/* ── Phase 11.1: Road route preview & fare card (only while idle) ──────── */}
      {activeTab === 'ride' && selectedPlace && destinationPlace && routeState.route && mapState.status === 'ready' && dispatchState.phase === 'idle' && (
        <RoutePreviewCard
          pickup={selectedPlace}
          destination={destinationPlace}
          route={routeState.route}
          selectedTier={routeState.selectedTier}
          onSelectTier={setSelectedTier}
          onRequestDispatch={requestDispatch}
          onClearDestination={handleClearDestination}
          isLoading={false}
        />
      )}

      {/* ── Phase 11.2 & 11.3: Real dispatch & vehicle tracking panel ────────── */}
      {activeTab === 'ride' && selectedPlace && mapState.status === 'ready' && (!destinationPlace || dispatchState.phase !== 'idle') && (
        <DispatchPanel
          placeName={selectedPlace.name}
          dispatchState={dispatchState}
          onRequestDispatch={requestDispatch}
          onCancelRide={cancelRide}
          isCancelling={isCancelling}
          onStartTrip={handleStartTrip}
          isStarting={isStarting}
          canStartTrip={canStartTrip}
          missingDestinationMessage={missingDestinationMessage}
          onCompleteTrip={completeRide}
          isCompleting={isCompleting}
          destinationPlace={destinationPlace}
          route={routeState.route}
          selectedTier={routeState.selectedTier}
          onReset={handleBookAnotherRide}
          approachStatus={driverApproach.status}
          remainingDistanceMeters={remainingDistanceMeters}
          remainingDurationSeconds={remainingDurationSeconds}
          isVehicleArrived={dispatchState.phase === 'arrived'}
          traceState={traceState}
          onRefreshTrace={refreshTrace}
          isTraceExpanded={isTraceExpanded}
          onToggleTraceExpand={setIsTraceExpanded}
        />
      )}
    </>
  );
}
